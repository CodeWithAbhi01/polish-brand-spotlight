// Helper: Get category by code
export const getCategoryByCode = (code: string) =>
  issueCategories.find((c) => c.code === code);

// Helper: Get categories grouped by SLA urgency
export const getCategoriesByUrgency = () => ({
  critical: issueCategories.filter((c) => c.defaultSlaHours <= 4),
  urgent: issueCategories.filter((c) => c.defaultSlaHours > 4 && c.defaultSlaHours <= 24),
  standard: issueCategories.filter((c) => c.defaultSlaHours > 24 && c.defaultSlaHours <= 72),
  extended: issueCategories.filter((c) => c.defaultSlaHours > 72),
});
