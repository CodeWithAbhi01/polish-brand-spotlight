// Helper: Get officials by tier
export const getOfficialsByTier = (tier: GovernanceOfficial["tier"]) =>
  governanceOfficials.filter((o) => o.tier === tier);

// Helper: Get onboarded officials
export const getOnboardedOfficials = () =>
  governanceOfficials.filter((o) => o.isOnboarded);

// Helper: Get officials by party
export const getOfficialsByParty = (partyCode: string) =>
  governanceOfficials.filter((o) => o.partyCode === partyCode);

// Helper: Search officials
export const searchOfficials = (query: string) => {
  const q = query.toLowerCase();
  return governanceOfficials.filter(
    (o) =>
      o.fullName.toLowerCase().includes(q) ||
      o.designation.toLowerCase().includes(q) ||
      o.jurisdictionName.toLowerCase().includes(q) ||
      (o.department && o.department.toLowerCase().includes(q))
  );
};
